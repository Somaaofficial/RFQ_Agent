# TAB 3 — RISK FLAGS
# ══════════════════════════════════════════════════════════════════════════════
def build_flags_tab(ws, risks: dict):
    ws.title = "🚩 Risk Flags"
    ws.sheet_view.showGridLines = False

    # title
    ws.row_dimensions[1].height = 30
    ws.merge_cells("A1:G1")
    c = ws["A1"]
    c.value     = "RISK FLAGS & COMPLIANCE ALERTS"
    c.font      = font(bold=True, color=WHITE, size=12)
    c.fill      = fill(RED_DK)
    c.alignment = align("center")

    # headers
    flag_hdrs = [
        ("Vendor",     28), ("Flag ID",    9),
        ("Severity",   11), ("Category",  18),
        ("Condition",  35), ("Detail",    52),
        ("Action Required", 38),
    ]
    ws.row_dimensions[2].height = 24
    for ci, (h, w) in enumerate(flag_hdrs, 1):
        ws.column_dimensions[get_column_letter(ci)].width = w
        c = ws.cell(row=2, column=ci, value=h)
        c.font      = font(bold=True, color=WHITE, size=9)
        c.fill      = fill(RED_DK)
        c.alignment = align("center", wrap=True)
        c.border    = border()

    current_row = 3
    for vname, rdata in risks.items():
        flags = rdata.get("all_flags", [])
        if not flags:
            # vendor row with no flags
            ws.row_dimensions[current_row].height = 20
            ws.merge_cells(
                f"A{current_row}:G{current_row}")
            c = ws.cell(row=current_row, column=1,
                        value=f"✅  {vname} — No flags detected")
            c.font      = font(size=9, color=GREEN_DK)
            c.fill      = fill(GREEN_LT)
            c.alignment = align("left")
            c.border    = border()
            current_row += 1
            continue

        for flag in flags:
            ws.row_dimensions[current_row].height = 40
            sev  = flag.get("severity", "AMBER")
            s_fg = (RED_DK   if sev=="RED"  else
                    AMBER_DK if sev=="AMBER" else
                    BLUE2)
            s_bg = (RED_LT   if sev=="RED"  else
                    AMBER_LT if sev=="AMBER" else
                    "E6F1FB")

            write(ws, current_row, 1, vname,
                  bold=True, fnt_size=9,
                  fnt_color=(RED_DK if sev=="RED" else "000000"),
                  bg=s_bg)
            write(ws, current_row, 2,
                  flag.get("flag_id",""),
                  h_align="center", bg=s_bg,
                  fnt_size=9, bold=True)

            # severity pill
            sev_icon = {"RED":"🔴 RED",
                        "AMBER":"🟡 AMBER",
                        "INFO":"ℹ INFO"}.get(sev, sev)
            write(ws, current_row, 3, sev_icon,
                  h_align="center",
                  fnt_color=s_fg, bold=True,
                  bg=s_bg, fnt_size=9)

            write(ws, current_row, 4,
                  flag.get("category",""),
                  bg=s_bg, fnt_size=9)
            write(ws, current_row, 5,
                  flag.get("condition",""),
                  bg=s_bg, fnt_size=9,
                  bold=(sev=="RED"), wrap=True)
            write(ws, current_row, 6,
                  flag.get("detail",""),
                  bg=s_bg, fnt_size=8,
                  italic=True, wrap=True)
            write(ws, current_row, 7,
                  flag.get("action",""),
                  bg=s_bg, fnt_size=8,
                  fnt_color=s_fg, bold=(sev=="RED"),
                  wrap=True)
            current_row += 1

    # summary section
    sum_row = current_row + 1
    ws.merge_cells(
        f"A{sum_row}:G{sum_row}")
    c = ws.cell(row=sum_row, column=1,
                value="DISQUALIFIED VENDORS:")
    c.font = font(bold=True, color=WHITE, size=9)
    c.fill = fill(RED_DK)
    c.alignment = align("left")

    disq_vendors = [
        v for v, r in risks.items()
        if r.get("disqualify_recommended")]
    for i, vname in enumerate(disq_vendors):
        dr = sum_row + 1 + i
        ws.merge_cells(f"A{dr}:G{dr}")
        c  = ws.cell(row=dr, column=1,
                     value=f"⛔  {vname} — "
                           f"DISQUALIFIED. "
                           f"Do not include in PO selection.")
        c.font      = font(bold=True, size=9,
                           color=RED_DK)
        c.fill      = fill(RED_LT)
        c.alignment = align("left")
        c.border    = border()


