# TAB 2 — SCORECARD
# ══════════════════════════════════════════════════════════════════════════════
def build_scorecard_tab(ws, scores: dict, risks: dict):
    ws.title = "🏆 Scorecard"
    ws.sheet_view.showGridLines = False

    # title
    ws.row_dimensions[1].height = 30
    ws.merge_cells("A1:I1")
    c = ws["A1"]
    c.value     = "VENDOR SCORECARD — WEIGHTED EVALUATION RESULTS"
    c.font      = font(bold=True, color=WHITE, size=12)
    c.fill      = fill(NAVY)
    c.alignment = align("center")

    # weights sub-header
    ws.row_dimensions[2].height = 18
    ws.merge_cells("A2:I2")
    c = ws["A2"]
    c.value = ("Price 40%  |  Delivery 25%  |  "
               "Payment 20%  |  Quality 10%  |  Penalty 5%")
    c.font      = font(italic=True, color=WHITE, size=9)
    c.fill      = fill(BLUE2)
    c.alignment = align("center")

    # column headers
    sc_headers = [
        ("Rank",       8), ("Vendor",     28),
        ("Price\n/40", 12), ("Delivery\n/25", 12),
        ("Payment\n/20", 12), ("Quality\n/10", 12),
        ("Penalty\n/5", 10), ("TOTAL\n/100", 12),
        ("Category",   16),
    ]
    ws.row_dimensions[3].height = 32
    for ci, (h, w) in enumerate(sc_headers, 1):
        ws.column_dimensions[get_column_letter(ci)].width = w
        c = ws.cell(row=3, column=ci, value=h)
        c.font      = font(bold=True, color=WHITE, size=9)
        c.fill      = fill(TEAL)
        c.alignment = align("center", wrap=True)
        c.border    = border()

    # sort vendors by score
    sorted_vendors = sorted(
        scores.items(),
        key=lambda x: x[1].get("total_score", 0),
        reverse=True
    )

    for ri, (vname, sdata) in enumerate(sorted_vendors):
        row  = 4 + ri
        rank = ri + 1
        ws.row_dimensions[row].height = 26
        cs   = sdata.get("criteria_scores", {})
        tot  = sdata.get("total_score", 0)
        cat  = sdata.get("rank_category", "")
        disq = risks.get(vname, {}).get(
            "disqualify_recommended", False)

        # row bg
        row_bg = (RED_LT    if disq      else
                  GREEN_LT  if rank == 1 else
                  "EAF6FF"  if rank == 2 else
                  PURPLE_LT if rank == 3 else
                  GRAY_LT   if ri%2==0   else WHITE)

        # rank
        medal  = {1:"🥇",2:"🥈",3:"🥉"}.get(rank, str(rank))
        write(ws, row, 1, medal,
              h_align="center", bg=row_bg, fnt_size=11,
              bold=(rank<=3))

        # vendor name
        write(ws, row, 2, vname, bold=(rank<=3),
              fnt_color=(RED_DK if disq else
                         GREEN_DK if rank==1 else "000000"),
              bg=row_bg, fnt_size=9)

        # criteria scores
        criteria_order = [
            "price","delivery","payment","quality","penalty"]
        for ci, crit in enumerate(criteria_order):
            crit_score = cs.get(crit, {})
            ws_score   = crit_score.get("weighted_score", 0)
            raw        = crit_score.get("raw_score", 0)
            reasoning  = crit_score.get("reasoning", "")
            col        = 3 + ci

            # colour based on raw score
            s_bg = (GREEN_LT if raw >= 80 else
                    AMBER_LT if raw >= 50 else
                    RED_LT   if raw < 50  else row_bg)
            if disq:
                s_bg = RED_LT

            c = ws.cell(row=row, column=col,
                        value=round(ws_score, 1))
            c.font      = font(bold=(raw>=80), size=9,
                               color=(GREEN_DK if raw>=80 else
                                      RED_DK   if raw<50  else
                                      "000000"))
            c.fill      = fill(s_bg)
            c.alignment = align("center")
            c.border    = border()
            c.comment   = None  # could add openpyxl Comment

        # total
        tot_bg = (RED_LT    if tot < 40  else
                  AMBER_LT  if tot < 65  else
                  GREEN_LT  if tot >= 80 else
                  GRAY_LT)
        c = ws.cell(row=row, column=8,
                    value=round(tot, 1))
        c.font      = font(bold=True, size=11,
                           color=(GREEN_DK if tot>=80 else
                                  RED_DK   if tot<50  else
                                  AMBER_DK))
        c.fill      = fill(tot_bg)
        c.alignment = align("center")
        c.border    = border()

        # category
        cat_icons = {
            "Recommended": ("✅ Recommended", GREEN_DK, GREEN_LT),
            "Consider":    ("🔵 Consider",    BLUE2,    "E6F1FB"),
            "Caution":     ("🟡 Caution",     AMBER_DK, AMBER_LT),
            "Avoid":       ("🔴 Avoid",       RED_DK,   RED_LT),
        }
        if disq:
            label, fc, bc = "⛔ DISQUALIFIED", RED_DK, RED_LT
        else:
            label, fc, bc = cat_icons.get(
                cat, (cat, "000000", row_bg))
        write(ws, row, 9, label,
              fnt_color=fc, bold=True,
              bg=bc, h_align="center", fnt_size=9)

    # reasoning section
    reason_row = 4 + len(sorted_vendors) + 2
    ws.row_dimensions[reason_row].height = 20
    ws.merge_cells(
        f"A{reason_row}:I{reason_row}")
    c = ws.cell(row=reason_row, column=1,
                value="SCORING REASONING (from Mistral AI):")
    c.font      = font(bold=True, color=WHITE, size=9)
    c.fill      = fill(TEAL)
    c.alignment = align("left")

    for ri, (vname, sdata) in enumerate(sorted_vendors):
        rr  = reason_row + 1 + ri
        ws.row_dimensions[rr].height = 18
        ws.merge_cells(f"A{rr}:I{rr}")
        rank = ri + 1
        summ = sdata.get("one_line_summary", "")
        c    = ws.cell(row=rr, column=1,
                       value=f"#{rank}  {vname}:  {summ}")
        c.font      = font(size=8, italic=True,
                           color=("5A5F6B"))
        c.fill      = fill(GRAY_LT if ri%2==0 else WHITE)
        c.alignment = align("left")


