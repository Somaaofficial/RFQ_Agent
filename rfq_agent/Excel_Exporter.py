def fill(hex_c):
    return PatternFill("solid",
                       start_color=hex_c,
                       end_color=hex_c)

def font(bold=False, color="000000",
         size=10, italic=False, name="Calibri"):
    return Font(bold=bold, color=color,
                size=size, italic=italic, name=name)

def border(style="thin", color="D0D0D0"):
    s = Side(style=style, color=color)
    return Border(left=s, right=s, top=s, bottom=s)

def align(h="left", v="center", wrap=False):
    return Alignment(horizontal=h,
                     vertical=v,
                     wrap_text=wrap)

def write(ws, row, col, value,
          bold=False, fnt_color="000000",
          fnt_size=10, bg=None,
          h_align="left", wrap=False,
          italic=False, bdr=True):
    cell            = ws.cell(row=row, column=col, value=value)
    cell.font       = font(bold=bold, color=fnt_color,
                           size=fnt_size, italic=italic)
    cell.alignment  = align(h_align, wrap=wrap)
    if bg:
        cell.fill   = fill(bg)
    if bdr:
        cell.border = border()
    return cell


