# TAB 4 — RECOMMENDATION
# ══════════════════════════════════════════════════════════════════════════════
def build_recommendation_tab(ws, extracted: dict,
                              scores: dict, risks: dict):
    ws.title = "✅ Recommendation"
    ws.sheet_view.showGridLines = False

    ws.row_dimensions[1].height = 34
    ws.merge_cells("A1:F1")
    c = ws["A1"]
    c.value     = "PURCHASE RECOMMENDATION NOTE"
    c.font      = font(bold=True, color=WHITE, size=13)
    c.fill      = fill(TEAL)
    c.alignment = align("center")

    # sort by score
    ranked = sorted(
        [(v, scores.get(v,{}), risks.get(v,{}))
         for v in extracted],
        key=lambda x: x[1].get("total_score", 0),
        reverse=True
    )

    # filter out disqualified
    qualified = [
        (v, s, r) for v, s, r in ranked
        if not r.get("disqualify_recommended", False)
    ]
    disqualified = [
        (v, s, r) for v, s, r in ranked
        if r.get("disqualify_recommended", False)
    ]

    # column widths
    for ci, w in enumerate([30,22,22,22,22,32], 1):
        ws.column_dimensions[get_column_letter(ci)].width = w

    current_row = 3

    def section_header(title, color=TEAL):
        nonlocal current_row
        ws.row_dimensions[current_row].height = 22
        ws.merge_cells(
            f"A{current_row}:F{current_row}")
        c = ws.cell(row=current_row, column=1,
                    value=title)
        c.font      = font(bold=True, color=WHITE, size=10)
        c.fill      = fill(color)
        c.alignment = align("left")
        current_row += 1

    def detail_row(label, value,
                   label_bg=GRAY_LT, val_bg=WHITE,
                   bold_val=False, val_color="000000"):
        nonlocal current_row
        ws.row_dimensions[current_row].height = 20
        c1 = ws.cell(row=current_row, column=1,
                     value=label)
        c1.font      = font(bold=True, size=9,
                            color=NAVY)
        c1.fill      = fill(label_bg)
        c1.alignment = align("left")
        c1.border    = border()

        ws.merge_cells(
            f"B{current_row}:F{current_row}")
        c2 = ws.cell(row=current_row, column=2,
                     value=value)
        c2.font      = font(bold=bold_val, size=9,
                            color=val_color)
        c2.fill      = fill(val_bg)
        c2.alignment = align("left", wrap=True)
        c2.border    = border()
        current_row += 1

    # ── TOP 3 QUALIFIED ───────────────────────────────────────────────────────
    for pos, (vname, sdata, rdata) in enumerate(
            qualified[:3], 1):
        medal  = {1:"🥇 FIRST CHOICE",
                  2:"🥈 SECOND CHOICE",
                  3:"🥉 THIRD CHOICE"}[pos]
        hdr_c  = {1:TEAL, 2:BLUE2, 3:PURPLE}[pos]
        section_header(f"{medal} — {vname}", hdr_c)

        f      = extracted.get(vname, {})
        total  = sdata.get("total_score", 0)
        summ   = sdata.get("one_line_summary", "")
        lc     = f.get("landed_cost", 0)
        dd     = f.get("delivery_days", "N/A")
        pay    = f.get("payment_terms", "N/A")
        adv    = f.get("advance_percentage", 0) or 0
        certs  = ", ".join(f.get("certifications",[])) or "None"
        pen    = f.get("penalty_clause", "Not mentioned")
        rl     = rdata.get("overall_risk_level","LOW")
        ac     = rdata.get("amber_count", 0)
        summ_r = rdata.get("risk_summary","")

        detail_row("Composite Score",
                   f"{total:.1f} / 100",
                   bold_val=True,
                   val_color=(GREEN_DK if total>=80 else AMBER_DK))
        detail_row("Landed Cost (all-in)",
                   f"INR {lc:.2f} per Kg")
        detail_row("Delivery Lead Time",
                   f"{dd} working days")
        detail_row("Payment Terms",   str(pay))
        detail_row("Advance Required",
                   f"{adv}%" if adv > 0 else "None — full credit")
        detail_row("Certifications",  certs)
        detail_row("Penalty Clause",
                   str(pen) if pen else "None stated")
        detail_row("Risk Level",      rl,
                   val_bg=(GREEN_LT if rl=="LOW" else
                           AMBER_LT if rl=="MEDIUM" else
                           RED_LT))
        detail_row("Amber Flags",
                   f"{ac} flag(s): {summ_r}" if ac>0
                   else "None")
        detail_row("Assessment",      summ,
                   val_bg=GRAY_LT)
        current_row += 1

    # ── DISQUALIFIED ──────────────────────────────────────────────────────────
    if disqualified:
        section_header(
            "⛔ DISQUALIFIED VENDORS — DO NOT SELECT",
            RED_DK)
        for vname, sdata, rdata in disqualified:
            rc   = rdata.get("red_count", 0)
            summ = rdata.get("risk_summary","")
            detail_row(
                vname,
                f"{rc} RED flag(s). {summ}",
                label_bg=RED_LT,
                val_bg=RED_LT,
                val_color=RED_DK)

    # ── approval block ────────────────────────────────────────────────────────
    current_row += 2
    section_header("APPROVAL", NAVY)
    detail_row("Recommended By", "RFQ Intelligence Agent (AI)")
    detail_row("Purchase Manager\nDecision", "_______________________")
    detail_row("Date", "_______________________")
    detail_row("Selected Vendor", "_______________________")
    detail_row("PO to be issued within", "2 working days of approval")


