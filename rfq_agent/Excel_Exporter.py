def build_excel_report(extracted: dict,
                       scores: dict,
                       risks: dict,
                       output_path: str = "RFQ_Comparison_Report.xlsx",
                       tech_scores: dict         = None,
                       supplier_history: dict    = None,
                       recommendation_reason: str = "",
                       recommendation_details: dict = None):
    wb = Workbook()
    # remove default sheet
    wb.remove(wb.active)

    # build all tabs
    ws1 = wb.create_sheet()
    build_comparison_tab(ws1, extracted, scores, risks)

    ws2 = wb.create_sheet()
    build_scorecard_tab(ws2, scores, risks)

    ws3 = wb.create_sheet()
    build_flags_tab(ws3, risks)

    ws4 = wb.create_sheet()
    build_recommendation_tab(ws4, extracted, scores, risks)

    wb.save(output_path)
    return output_path


