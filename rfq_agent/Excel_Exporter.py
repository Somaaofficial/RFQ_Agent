# TAB 1 — VENDOR COMPARISON
# ══════════════════════════════════════════════════════════════════════════════
def build_comparison_tab(ws, extracted: dict,
                         scores: dict, risks: dict):
    ws.title       = "📊 Vendor Comparison"
    ws.sheet_view.showGridLines = False

    # ── title row ─────────────────────────────────────────────────────────────
    ws.row_dimensions[1].height = 34
    ws.merge_cells("A1:P1")
    c = ws["A1"]
    c.value     = "RFQ VENDOR COMPARISON — HR Steel Sheets 3mm | Qty: 10,000 Kg"
    c.font      = font(bold=True, color=WHITE, size=13)
    c.fill      = fill(NAVY)
    c.alignment = align("center")

    # ── sub-header ────────────────────────────────────────────────────────────
    ws.row_dimensions[2].height = 18
    ws.merge_cells("A2:P2")
    c = ws["A2"]
    c.value     = (f"Generated by RFQ Intelligence Agent  |  "
                   f"Procurement Policy Rev 4.1 Applied  |  "
                   f"All prices in INR")
    c.font      = font(italic=True, color=WHITE, size=8)
    c.fill      = fill(BLUE2)
    c.alignment = align("center")

    # ── column headers ────────────────────────────────────────────────────────
    headers = [
        ("Rank",            8),  ("Vendor Name",      28),
        ("Unit Price\n(INR/Kg)", 14), ("Freight\n(INR/Kg)", 12),
        ("Incoterm",        13), ("GST %",             8),
        ("Landed Cost\n(INR/Kg)", 14), ("Delivery\n(Days)",  12),
        ("Payment\nTerms",  18), ("Advance\n%",         9),
        ("Validity\n(Days)", 11), ("Certifications",   20),
        ("Warranty\n(Mo)",   10), ("Penalty\nClause",  20),
        ("Price\nFirm",      9), ("Risk\nLevel",       11),
    ]

    ws.row_dimensions[3].height = 36
    for col_idx, (h, w) in enumerate(headers, 1):
        ws.column_dimensions[get_column_letter(col_idx)].width = w
        c = ws.cell(row=3, column=col_idx, value=h)
        c.font       = font(bold=True, color=WHITE, size=9)
        c.fill       = fill(NAVY)
        c.alignment  = align("center", wrap=True)
        c.border     = border("thin", "FFFFFF")

    # ── rank vendors by score ─────────────────────────────────────────────────
    vendor_list = []
    for vname, fields in extracted.items():
        score_data = scores.get(vname, {})
        risk_data  = risks.get(vname,  {})
        vendor_list.append({
            "name":    vname,
            "fields":  fields,
            "score":   score_data.get("total_score", 0),
            "risk":    risk_data
        })
    vendor_list.sort(key=lambda x: x["score"], reverse=True)

    # ── data rows ─────────────────────────────────────────────────────────────
    for row_offset, v in enumerate(vendor_list):
        row        = 4 + row_offset
        ws.row_dimensions[row].height = 30
        f          = v["fields"]
        risk       = v["risk"]
        score      = v["score"]
        rank       = row_offset + 1
        disq       = risk.get("disqualify_recommended", False)
        risk_level = risk.get("overall_risk_level", "MEDIUM")
        red_count  = risk.get("red_count", 0)
        amb_count  = risk.get("amber_count", 0)

        # row background
        if disq:
            row_bg = RED_LT
        elif rank == 1:
            row_bg = GREEN_LT
        elif rank == 2:
            row_bg = "EAF6FF"
        elif rank == 3:
            row_bg = PURPLE_LT
        elif amb_count > 0:
            row_bg = AMBER_LT
        else:
            row_bg = GRAY_LT if row_offset % 2 == 0 else WHITE

        # rank cell
        rank_label = {1:"🥇 1st", 2:"🥈 2nd",
                      3:"🥉 3rd"}.get(rank, f"  #{rank}")
        if disq:
            rank_label = "⛔ DISQ"
        write(ws, row, 1, rank_label,
              bold=True, fnt_color=NAVY if not disq else RED_DK,
              bg=row_bg, h_align="center", fnt_size=9)

        # vendor name
        write(ws, row, 2, v["name"],
              bold=(rank <= 3), fnt_size=9,
              fnt_color=GREEN_DK if rank==1 else
                        RED_DK if disq else "000000",
              bg=row_bg)

        # unit price
        up = f.get("unit_price")
        write(ws, row, 3, f"₹{up:.2f}" if up else "N/A",
              h_align="right", bg=row_bg, fnt_size=9)

        # freight
        fr = f.get("freight_per_unit", 0) or 0
        write(ws, row, 4,
              f"₹{fr:.2f}" if fr > 0 else "Included",
              h_align="right", bg=row_bg, fnt_size=9,
              italic=(fr == 0))

        # incoterm
        write(ws, row, 5, f.get("incoterm", "N/A"),
              h_align="center", bg=row_bg, fnt_size=9)

        # gst
        gst = f.get("gst_rate", 18)
        write(ws, row, 6, f"{gst}%",
              h_align="center", bg=row_bg, fnt_size=9)

        # landed cost — highlight lowest
        lc = f.get("landed_cost", 0) or 0
        all_lc = [vv["fields"].get("landed_cost", 0) or 0
                  for vv in vendor_list]
        is_lowest = lc > 0 and lc == min(c for c in all_lc if c > 0)
        lc_cell = write(ws, row, 7, f"₹{lc:.2f}" if lc else "N/A",
                        bold=is_lowest,
                        fnt_color=GREEN_DK if is_lowest else "000000",
                        bg=GREEN_LT if is_lowest else row_bg,
                        h_align="right", fnt_size=9)

        # delivery days
        dd = f.get("delivery_days")
        dd_bg = (GREEN_LT if dd and dd <= 10 else
                 AMBER_LT if dd and dd <= 21 else
                 RED_LT   if dd and dd > 21 else row_bg)
        write(ws, row, 8, dd if dd else "N/A",
              h_align="center", bg=dd_bg, fnt_size=9)

        # payment terms
        write(ws, row, 9,
              str(f.get("payment_terms", "N/A"))[:30],
              bg=row_bg, fnt_size=9)

        # advance %
        adv    = f.get("advance_percentage", 0) or 0
        adv_bg = (RED_LT   if adv >= 100 else
                  AMBER_LT if adv >= 25  else
                  GREEN_LT if adv == 0   else row_bg)
        write(ws, row, 10,
              f"{adv}%" if adv > 0 else "None",
              h_align="center",
              fnt_color=RED_DK if adv >= 50 else "000000",
              bold=(adv >= 50),
              bg=adv_bg, fnt_size=9)

        # validity
        val    = f.get("quote_validity_days", 30) or 30
        val_bg = (RED_LT   if val <= 5  else
                  AMBER_LT if val <= 15 else row_bg)
        write(ws, row, 11, f"{val} days",
              h_align="center", bg=val_bg, fnt_size=9)

        # certifications
        certs = f.get("certifications", []) or []
        cert_str = ", ".join(certs) if certs else "❌ NONE"
        cert_bg  = (RED_LT   if not certs else
                    AMBER_LT if len(certs) == 1 else row_bg)
        write(ws, row, 12, cert_str,
              fnt_color=RED_DK if not certs else "000000",
              bg=cert_bg, fnt_size=9, wrap=True)

        # warranty
        war    = f.get("warranty_months", 0) or 0
        war_bg = (RED_LT   if war == 0   else
                  AMBER_LT if war < 12   else row_bg)
        write(ws, row, 13,
              f"{war} mo" if war > 0 else "None",
              h_align="center", bg=war_bg, fnt_size=9)

        # penalty clause
        pen = f.get("penalty_clause")
        write(ws, row, 14,
              pen if pen else "⚠ Not offered",
              fnt_color=RED_DK if not pen else "000000",
              italic=not bool(pen),
              bg=AMBER_LT if not pen else row_bg,
              fnt_size=8, wrap=True)

        # price firm
        pf    = f.get("price_firm")
        pf_bg = GREEN_LT if pf else RED_LT
        write(ws, row, 15,
              "✅ Firm" if pf else "⚠ Variable",
              h_align="center",
              fnt_color=GREEN_DK if pf else RED_DK,
              bold=True, bg=pf_bg, fnt_size=9)

        # risk level
        risk_colors = {
            "LOW":      (GREEN_DK, GREEN_LT),
            "MEDIUM":   (AMBER_DK, AMBER_LT),
            "HIGH":     (RED_DK,   RED_LT),
            "CRITICAL": (RED_DK,   RED_LT),
        }
        rc, rb = risk_colors.get(risk_level, ("000000", row_bg))
        rl_icon = {"LOW":"🟢","MEDIUM":"🟡",
                   "HIGH":"🔴","CRITICAL":"🔴"}.get(risk_level,"")
        write(ws, row, 16,
              f"{rl_icon} {risk_level}",
              h_align="center",
              fnt_color=rc, bold=(risk_level in ["HIGH","CRITICAL"]),
              bg=rb, fnt_size=9)

    # ── legend ────────────────────────────────────────────────────────────────
    leg_row = 4 + len(vendor_list) + 1
    ws.merge_cells(
        f"A{leg_row}:{get_column_letter(16)}{leg_row}")
    c = ws.cell(row=leg_row, column=1,
                value=("🥇 Recommended   🔵 Consider   "
                       "🟡 Caution — amber flags present   "
                       "⛔ DISQUALIFIED — red flags present   "
                       "🟩 Lowest landed cost"))
    c.font      = font(italic=True, color="5A5F6B", size=8)
    c.fill      = fill(GRAY_LT)
    c.alignment = align("center")


